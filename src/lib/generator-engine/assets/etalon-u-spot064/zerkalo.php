<p>Первый — SSL-сертификат. Кликните на замок слева от адресной строки браузера. В сертификате должно быть указано имя компании-владельца Union и срок действия не менее года. Если сертификат самоподписанный или выдан на другое юридическое лицо — закрывайте вкладку. Второй признак — совпадение дизайна и функционала. Официальное зеркало копирует основной сайт на 100%: те же разделы меню, тот же список игр, те же бонусные предложения. Если на «зеркале» отсутствует раздел live-казино или изменён логотип — это подделка.</p>

<dd class="union_games_glossary_definition">Процент ставок, который автомат возвращает игрокам в долгосрочной перспективе. Например, RTP 96% означает, что из 100 ₽ ставок игрок в среднем получит обратно 96 ₽. Показатель рассчитывается на миллионах спинов и не гарантирует результат в короткой сессии.</dd>
</div>
<div class="union_games_glossary_entry">
<dt class="union_games_glossary_term">Волатильность (дисперсия)</dt>
<dd class="union_games_glossary_definition">Показатель частоты и размера выигрышей. Низкая волатильность — частые мелкие выплаты, подходит для длительной игры с небольшим банкроллом. Высокая волатильность — редкие, но крупные выигрыши, требует терпения и большего запаса средств. Средняя волатильность — баланс между частотой и размером призов.</dd>
</div>
<div class="union_games_glossary_entry">
<dt class="union_games_glossary_term">Wild (Вайлд)</dt>
<dd class="union_games_glossary_definition">Специальный символ, который заменяет любые другие символы (кроме Scatter и Bonus) для формирования выигрышных комбинаций. Бывают обычные, расширяющиеся (Expanding Wild), липкие (Sticky Wild) и блуждающие (Walking Wild).</dd>
</div>
<div class="union_games_glossary_entry">
<dt class="union_games_glossary_term">Scatter (Скаттер)</dt>
<dd class="union_games_glossary_definition">Символ, который запускает бонусные раунды или фриспины независимо от позиции на барабанах. Обычно требуется три и более Scatter на экране. Не заменяется Wild.</dd>
</div>
<div class="union_games_glossary_entry">
<dt class="union_games_glossary_term">Фриспины (Free Spins)</dt>
<dd class="union_games_glossary_definition">Бесплатные вращения барабанов, которые запускаются символами Scatter или покупаются за фиксированную сумму (функция Buy Bonus). Во время фриспинов часто действуют множители выигрышей, дополнительные Wild или увеличенное количество линий.</dd>
</div>
<div class="union_games_glossary_entry">
<dt class="union_games_glossary_term">Множитель (Multiplier)</dt>
<dd class="union_games_glossary_definition">Коэффициент, который умножает выигрыш. Например, множитель ×3 утроит сумму приза. Множители могут быть фиксированными или прогрессивными (растут с каждым последовательным выигрышем).</dd>
</div>
<div class="union_games_glossary_entry">
<dt class="union_games_glossary_term">Прогрессивный джекпот</dt>
<dd class="union_games_glossary_definition">Джекпот, который растёт с каждой ставкой игроков по всей сети казино. Часть каждой ставки (обычно 1–5%) добавляется в общий призовой фонд. Джекпот выпадает случайно или при выполнении определённых условий (например, пять символов джекпота на линии).</dd>
</div>
<div class="union_games_glossary_entry">
<dt class="union_games_glossary_term">Каскадные барабаны (Cascading Reels)</dt>
<dd class="union_games_glossary_definition">Механика, при которой символы выигрышной комбинации исчезают, а на их место падают новые. Если новые символы образуют выигрыш, процесс повторяется. Один спин может принести несколько последовательных выплат.</dd>
</div>
<div class="union_games_glossary_entry">
<dt class="union_games_glossary_term">Megaways</dt>
<dd class="union_games_glossary_definition">Лицензионная механика от Big Time Gaming, при которой количество символов на каждом барабане меняется случайным образом (от 2 до 7). Число способов выиграть достигает 117 649. Популярные слоты: Bonanza, Extra Chilli, Gonzo's Quest Megaways.</dd>
</div>
<div class="union_games_glossary_entry">
<dt class="union_games_glossary_term">Hold & Win (Respins)</dt>
<dd class="union_games_glossary_definition">Бонусная игра, в которой специальные символы (обычно монеты с числовыми значениями) фиксируются на экране, а остальные позиции вращаются заново. Каждый новый символ сбрасывает счётчик респинов. Раунд заканчивается, когда респины исчерпаны или все позиции заполнены.</dd>
</div>
</dl>
</div>
<p class="union_games_glossary_footer">Понимание этих терминов поможет вам выбрать слот под свой стиль игры и банкролл. Если вы новичок, начните с автоматов низкой или средней волатильности и RTP выше 96%. Опытные игроки могут искать высоковолатильные слоты с потенциалом крупных выигрышей.</p>
</section>


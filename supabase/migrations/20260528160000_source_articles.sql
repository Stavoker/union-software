-- Глобальний корпус текстів для Copy Engine / генерації контенту (усі користувачі — read).
-- Сумісно з admin-text-gen/supabase/schema.sql; id — identity, embedding — vector(1536).

create extension if not exists vector;

create table if not exists public.source_articles (
  id bigint generated by default as identity primary key,
  platform text not null,
  brand text not null,
  language text not null,
  category text not null,
  subcategory text null,
  tone text not null,
  has_cta text not null,
  content text not null,
  source_url text not null,
  title text not null,
  notes text null,
  parsed_at date null,
  indexing_status text not null default 'pending',
  embedding public.vector(1536) null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint source_articles_source_url_key unique (source_url),
  constraint source_articles_indexing_status_check check (
    indexing_status = any (
      array['pending', 'processing', 'indexed', 'failed', 'skipped']::text[]
    )
  )
);

comment on table public.source_articles is
  'Референсні статті для генерації текстів сайту (Copy Engine). Спільна для всіх користувачів; редагування — admin.';
comment on column public.source_articles.embedding is
  'OpenAI text-embedding-3-small / ada-002 — 1536 dims; для similarity search на сервері (service_role).';
comment on column public.source_articles.indexing_status is
  'Статус індексації/ембеддингу: pending | processing | indexed | failed | skipped';

create index if not exists source_articles_language_category_idx
  on public.source_articles (language, category);

create index if not exists source_articles_brand_idx
  on public.source_articles (brand);

create index if not exists source_articles_indexing_status_idx
  on public.source_articles (indexing_status)
  where indexing_status <> 'indexed';

-- Пошук за cosine similarity (після наповнення embedding)
create index if not exists source_articles_embedding_hnsw_idx
  on public.source_articles using hnsw (embedding vector_cosine_ops)
  with (m = 16, ef_construction = 64);

create or replace function public.touch_source_articles_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists trg_source_articles_updated_at on public.source_articles;
create trigger trg_source_articles_updated_at
  before update on public.source_articles
  for each row
  execute function public.touch_source_articles_updated_at();

-- is_union_admin() — з міграції generator_user_brands; дублюємо для idempotent apply
create or replace function public.is_union_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.profiles p
    where p.id = auth.uid()
      and p.role = 'admin'
  );
$$;

alter table public.source_articles enable row level security;

drop policy if exists source_articles_select_authenticated on public.source_articles;
create policy source_articles_select_authenticated
  on public.source_articles
  for select
  to authenticated
  using (true);

drop policy if exists source_articles_admin_write on public.source_articles;
create policy source_articles_admin_write
  on public.source_articles
  for all
  to authenticated
  using (public.is_union_admin())
  with check (public.is_union_admin());

